class DemandLeakageDetector:
    """
    Detects demand leakage (expected > observed) indicating potential competitor capture.
    """
    
    def __init__(self, min_confidence_threshold: float = 0.5):
        self.min_confidence_threshold = min_confidence_threshold
        
    def compute_leakage(self, 
                       predicted_consumption: pd.Series,
                       observed_consumption: pd.Series,
                       customer_volatility: pd.Series,
                       model_confidence: float = 0.85) -> pd.DataFrame:
        """
        Compute demand leakage for customers.
        
        Formula:
            base_gap = (predicted - observed) / predicted
            leakage_score = base_gap × volatility_factor × confidence
        
        Args:
            predicted_consumption: Expected monthly consumption
            observed_consumption: Actual monthly consumption
            customer_volatility: Historical variance in purchases
            model_confidence: Confidence in forecasting model
            
        Returns:
            DataFrame with leakage metrics
        """
        results = pd.DataFrame({
            'predicted': predicted_consumption,
            'observed': observed_consumption
        })
        
        # Avoid division by zero
        results['base_gap'] = np.where(
            results['predicted'] > 0,
            (results['predicted'] - results['observed']) / results['predicted'],
            0
        )
        
        # Normalize by customer volatility and model confidence
        results['leakage_score'] = (
            np.maximum(results['base_gap'], 0)  # Only positive gaps
            * customer_volatility.fillna(1.0)   # Account for variance
            * model_confidence
        )
        
        # Clip to 0-1 range
        results['leakage_score'] = results['leakage_score'].clip(0, 1)
        
        return results
    
    def filter_significant_leakage(self, leakage_df: pd.DataFrame, 
                                   min_gap_units: int = 10) -> pd.DataFrame:
        """Filter to significant leakage events only"""
        return leakage_df[
            (leakage_df['leakage_score'] > self.min_confidence_threshold) &
            ((leakage_df['predicted'] - leakage_df['observed']) >= min_gap_units)
        ]


