class CommoditySignalGenerator:
    """
    Orchestrates the complete commodity engine pipeline.
    Combines all components to generate actionable signals.
    """
    
    def __init__(self, sales_df: pd.DataFrame, clients_df: pd.DataFrame, 
                products_df: pd.DataFrame):
        self.sales_df = sales_df
        self.clients_df = clients_df
        self.products_df = products_df
        
        self.clusterer = CommodityCustomerCluster()
        self.forecaster = DemandForecaster()
        self.leakage_detector = DemandLeakageDetector()
        self.scorer = CaptureScoringEngine()
        
    def generate_signals(self) -> List[CommoditySignal]:
        """
        Run complete pipeline and generate signals.
        
        Steps:
        1. Cluster customers
        2. Forecast demand
        3. Detect leakage
        4. Score opportunities
        5. Generate explanations
        
        Returns:
            List of CommoditySignal objects
        """
        logger.info("Starting commodity engine pipeline...")
        
        # Step 1: Clustering
        logger.info("Step 1: Clustering customers...")
        cluster_features = self.clusterer.prepare_features(self.sales_df, self.clients_df)
        self.clusterer.fit(cluster_features)
        cluster_assignments = self.clusterer.predict(cluster_features)
        
        # Step 2: Forecasting
        logger.info("Step 2: Forecasting demand...")
        forecast_features, forecast_target = self.forecaster.prepare_features(
            self.sales_df, cluster_assignments, self.clients_df
        )
        self.forecaster.train(forecast_features, forecast_target)
        predictions = self.forecaster.predict(forecast_features)
        
        # Step 3: Leakage detection
        logger.info("Step 3: Detecting demand leakage...")
        observed = self._get_observed_consumption()
        leakage_results = self.leakage_detector.compute_leakage(
            pd.Series(predictions),
            observed
        )
        
        # Step 4: Scoring
        logger.info("Step 4: Scoring opportunities...")
        scored = self.scorer.score_opportunities(
            leakage_results, self.clients_df, observed, self.forecaster
        )
        actions = self.scorer.generate_action_recommendations(scored)
        
        # Step 5: Generate signals
        logger.info("Step 5: Generating signals...")
        signals = self._create_signals(scored, actions)
        
        logger.info(f"Generated {len(signals)} signals")
        return signals
    
