def _compute_regression_metrics(
    actual: pd.Series | np.ndarray,
    predicted: pd.Series | np.ndarray,
    *,
    baseline: pd.Series | np.ndarray | None = None,
) -> dict:
    actual_array = np.asarray(actual, dtype=float)
    predicted_array = np.asarray(predicted, dtype=float)
    residuals = actual_array - predicted_array
    rmse = float(np.sqrt(np.mean(np.square(residuals))))
    mae = float(np.mean(np.abs(residuals)))
    denominator = float(np.sum(np.abs(actual_array))) + 1e-9
    wmape = float(np.sum(np.abs(residuals)) / denominator)
    non_zero_mask = actual_array != 0
    if non_zero_mask.any():
        mape_nonzero = float(
            np.mean(np.abs((actual_array[non_zero_mask] - predicted_array[non_zero_mask]) / actual_array[non_zero_mask]))
        )
    else:
        mape_nonzero = 0.0
    metrics = {
        "rmse": rmse,
        "mae": mae,
        "wmape": wmape,
        "mape_nonzero": mape_nonzero,
        "r2": float(r2_score(actual_array, predicted_array)) if len(actual_array) > 1 else 0.0,
    }
    if baseline is not None:
        baseline_array = np.asarray(baseline, dtype=float)
        baseline_residuals = actual_array - baseline_array
        baseline_rmse = float(np.sqrt(np.mean(np.square(baseline_residuals))))
        baseline_mae = float(np.mean(np.abs(baseline_residuals)))
        baseline_wmape = float(np.sum(np.abs(baseline_residuals)) / denominator)
        metrics.update(
            {
                "baseline_rmse": baseline_rmse,
                "baseline_mae": baseline_mae,
                "baseline_wmape": baseline_wmape,
                "rmse_improvement_vs_baseline": baseline_rmse - rmse,
                "wmape_improvement_vs_baseline": baseline_wmape - wmape,
            }
        )
    return metrics


