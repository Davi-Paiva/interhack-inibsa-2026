def _parquet_engine() -> str:
    if importlib.util.find_spec("pyarrow") is not None:
        return "pyarrow"
    if importlib.util.find_spec("fastparquet") is not None:
        return "fastparquet"
    raise RuntimeError(
        "Parquet output requires either 'pyarrow' or 'fastparquet' to be installed."
    )


def _write_parquet(df: pd.DataFrame, output_path: Path) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(
        output_path,
        index=False,
        compression="snappy",
        engine=_parquet_engine(),
    )
    return output_path


def _write_json(payload: dict, output_path: Path) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=True),
        encoding="utf-8",
    )
    return output_path


def _write_pickle(payload: object, output_path: Path) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("wb") as handle:
        pickle.dump(payload, handle)
    return output_path


def _read_pickle(path: Path) -> object:
    if not path.exists():
        raise FileNotFoundError(f"Required pickle artifact was not found: {path}")
    with path.open("rb") as handle:
        return pickle.load(handle)


def _read_frame(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Required input was not found: {path}")
    if path.suffix.lower() == ".csv":
        for encoding in ("utf-8-sig", "utf-8", "latin-1"):
            try:
                return pd.read_csv(path, encoding=encoding, low_memory=False)
            except UnicodeDecodeError:
                continue
        raise UnicodeDecodeError("utf-8", b"", 0, 1, f"Could not decode {path}")
    if path.suffix.lower() == ".parquet":
        return pd.read_parquet(path)
    raise ValueError(f"Unsupported file format for {path}")


def _resolve_existing_path(base_dir: Path, candidates: Iterable[str], label: str) -> Path:
    for candidate in candidates:
        candidate_path = base_dir / candidate
        if candidate_path.exists():
            return candidate_path
    raise FileNotFoundError(
        f"Missing required {label} input in {base_dir}. "
        f"Expected one of: {', '.join(candidates)}"
    )


def _normalize_identifier(series: pd.Series) -> pd.Series:
    return series.astype("string").str.strip()


def _normalize_boolean(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False).astype(bool)
    normalized = (
        series.astype("string")
        .str.strip()
        .str.lower()
        .map(
            {
                "true": True,
                "false": False,
                "1": True,
                "0": False,
                "yes": True,
                "no": False,
                "nan": False,
                "<na>": False,
            }
        )
    )
    return normalized.fillna(False).astype(bool)


def _normalize_frame_types(df: pd.DataFrame) -> pd.DataFrame:
    normalized = df.copy()
    for column in ("client_id", "customer_id", "product_id", "product_family", "family", "postal_code", "province", "category", "analytic_block"):
        if column in normalized.columns:
            normalized[column] = _normalize_identifier(normalized[column])
    for column in ("is_active_customer", "is_return", "is_campaign_period", "is_month_end", "is_quarter_end"):
        if column in normalized.columns:
            normalized[column] = _normalize_boolean(normalized[column])
    for column in normalized.columns:
        if column.endswith("_date") or column in {"date", "forecast_date", "snapshot_date"}:
            normalized[column] = pd.to_datetime(normalized[column], errors="coerce")
    return normalized


